import { Timestamp } from "firebase-admin/firestore";
import { financeOrder, summarizeFinance, wibRange, type FinanceRow } from "@/lib/finance";
import { commerceServices } from "@/lib/server/commerce";

export const runtime = "nodejs";
const headers = { "Cache-Control": "private, no-store", Vary: "Authorization" };
const MAX_ORDERS = 10_000;

const json = (data: unknown, status = 200) => Response.json(data, { status, headers });

export async function GET(request: Request) {
  const bearer = request.headers.get("authorization");
  if (!bearer?.startsWith("Bearer ") || bearer.length > 8192) return json({ error: "Masuk sebagai admin." }, 401);

  try {
    const { app, db } = commerceServices();
    const { getAuth } = await import("firebase-admin/auth");
    const user = await getAuth(app).verifyIdToken(bearer.slice(7), true).catch(() => null);
    if (!user || !/^[A-Za-z0-9_-]{1,128}$/.test(user.uid)) return json({ error: "Masuk sebagai admin." }, 401);
    if (!(await db.collection("market_admins").doc(user.uid).get()).exists) return json({ error: "Akses admin diperlukan." }, 403);

    const query = new URL(request.url).searchParams;
    const from = query.get("from"), to = query.get("to");
    const range = wibRange(from, to);
    if (!range) return json({ error: "Pilih rentang tanggal yang valid, maksimal 365 hari." }, 400);

    const result = await db.collection("market_orders")
      .where("paid_at", ">=", Timestamp.fromMillis(range.start))
      .where("paid_at", "<", Timestamp.fromMillis(range.endExclusive))
      .orderBy("paid_at", "desc")
      .select("amount_idr", "status", "payment_mode", "currency", "paid_at", "provider_fee_idr", "provider_net_idr")
      .limit(MAX_ORDERS + 1).get();
    if (result.size > MAX_ORDERS) return json({ error: "Pilih rentang yang lebih pendek untuk melihat semua transaksi." }, 422);

    const rows: FinanceRow[] = [];
    for (const snap of result.docs) {
      const row = snap.data();
      const payment = financeOrder(snap.id, { ...row, paid_at: row.paid_at?.toDate?.() });
      if (payment) rows.push(payment);
    }
    if (query.get("format") === "csv") {
      const lines = [["Pesanan", "Tanggal pembayaran (UTC)", "Nominal (IDR)", "Biaya (IDR)", "Neto setelah biaya (IDR)"]];
      for (const row of rows) {
        // Order IDs generated by checkout are UUIDs. Sanitize legacy IDs before CSV export.
        const id = /^[A-Za-z0-9_-]{1,128}$/.test(row.id) && !row.id.startsWith("-") ? row.id : "";
        lines.push([id, row.date, String(row.gross), String(row.fee ?? ""), String(row.net ?? "")]);
      }
      return new Response("\uFEFF" + lines.map(line => line.join(",")).join("\r\n"), {
        headers: { ...headers, "Content-Type": "text/csv; charset=utf-8",
          "Content-Disposition": 'attachment; filename="anshel-qr-pembayaran-' + from + "-sampai-" + to + '.csv"' },
      });
    }
    return json(summarizeFinance(rows, range.start, range.endExclusive));
  } catch {
    return json({ error: "Data keuangan belum dapat dimuat." }, 503);
  }
}
